/**
 * Exports the measured benchmark results (docs/benchmarks/*.json) into a compact file the
 * website renders on /lab — content/benchmarks.json. docs/ is not deployed, so the site
 * needs its own copy; this script is the only way that copy is produced, so the page can
 * never show a number that was not measured.
 *   cd tools && node --no-warnings bench/export-site.ts
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT } from "../kb/content.ts";
import { EVAL_SET } from "./eval-set.ts";
import { draftAcceptance } from "./metrics.ts";

const dir = path.join(ROOT, "docs", "benchmarks");
const read = (f: string) => JSON.parse(readFileSync(path.join(dir, f), "utf8"));
type Row = { id: string; kind?: string; pass?: boolean; mode?: string; replaced?: boolean; issues?: string[]; keywords?: number | null; error?: string };

const finalFiles = ["llm-benchmark.json", ...readdirSync(dir).filter((f) => /^llm-benchmark-.+\.json$/.test(f) && f !== "llm-benchmark-preliminary.json").sort()];
const speed = existsSync(path.join(dir, "llama-bench.json")) ? read("llama-bench.json") : null;
const short = (name: string) => name.replace(/-Instruct$|-it$/, "");

const models = [];
const outcomes: Record<string, { id: string; outcome: "replaced" | "wrong" | "error"; issues: string[] }[]> = {};
for (const f of finalFiles) {
  const run = read(f);
  for (const r of run.results) {
    const rows: Row[] = r.rows;
    const ok = rows.filter((x) => "pass" in x);
    const acc = draftAcceptance(ok);
    const sp = speed?.results.find((s: { model: string }) => short(s.model) === short(r.summary.model));
    models.push({
      name: r.summary.model,
      params: r.summary.params,
      license: r.summary.license,
      fileMB: r.summary.fileMB,
      correct: ok.filter((x) => x.pass).length,
      cases: ok.length,
      draftsAccepted: acc.accepted,
      draftsRequested: acc.called,
      keywordCoverage: Math.round(r.summary.keywordCoverage * 100),
      unknownDeclined: r.summary.unknownDeclined,
      decodeTokS: sp ? sp.decodeTokS : null,
      prefillTokS: sp ? sp.prefillTokS : null,
      runAt: run.runAt,
      source: `docs/benchmarks/${f}`,
    });
    outcomes[r.summary.model] = rows
      .filter((x) => !("pass" in x) || x.pass === false || x.replaced)
      .map((x) => ({ id: x.id, outcome: !("pass" in x) ? "error" : x.pass === false ? "wrong" : "replaced", issues: (x.issues ?? (x.error ? [x.error] : [])).slice(0, 3) }));
  }
}
const agentsRun = existsSync(path.join(dir, "agent-execution.json")) ? read("agent-execution.json") : null;
const out = {
  note: "Generated by tools/bench/export-site.ts from docs/benchmarks — do not edit by hand.",
  hardware: read("llm-benchmark.json").hardware,
  speedTool: speed?.tool ?? null,
  questions: Object.fromEntries(EVAL_SET.map((c) => [c.id, c.q])),
  models,
  outcomes,
  agentRun: agentsRun ? { runAt: agentsRun.runAt, model: agentsRun.model, scenarios: agentsRun.scenarios, passed: agentsRun.passed } : null,
};
writeFileSync(path.join(ROOT, "content", "benchmarks.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`content/benchmarks.json: ${models.length} models, ${Object.values(outcomes).flat().length} drill-down rows`);
