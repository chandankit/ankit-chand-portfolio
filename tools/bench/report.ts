/**
 * Turns the measured benchmark files into docs/benchmarks/README.md, so every
 * number in the docs comes straight from a run (nothing typed by hand).
 *   node bench/report.ts
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT } from "../kb/content.ts";

const dir = path.join(ROOT, "docs", "benchmarks");
const read = (f: string) => (existsSync(path.join(dir, f)) ? JSON.parse(readFileSync(path.join(dir, f), "utf8")) : null);
const final = read("llm-benchmark.json");
const prelim = read("llm-benchmark-preliminary.json");
const gpu = read("webgpu-benchmark.json");
const speed = read("llama-bench.json");
const pct = (x: number) => `${Math.round(x * 100)}%`;
const n1 = (x: number | null | undefined) => (x === null || x === undefined ? "—" : x.toFixed(1));

type Summary = {
  model: string; params: string; quant: string; license: string; fileMB: number; ramMB: number | null; cases: number; errors: number;
  passRate: number; validatorAcceptRate: number; replacedByValidator: number; keywordCoverage: number; unknownDeclined: string;
  avgSecondsPerAnswer: number; avgGenerationSeconds: number; tokensPerSecond: number | null; promptTokensPerSecond?: number | null;
};

function table(results: { summary: Summary }[]) {
  const head = "| Model | Params | Quant | File | RAM | Final answers correct | Model drafts accepted by validator | Replaced | Keyword coverage | Unknowns declined | Prefill tok/s | Decode tok/s | Avg s / answer |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|";
  const rows = results.map(({ summary: s }) =>
    `| ${s.model} (${s.license}) | ${s.params} | ${s.quant} | ${s.fileMB} MB | ${s.ramMB ?? "—"} MB | ${pct(s.passRate)} (${Math.round(s.passRate * s.cases)}/${s.cases}) | ${pct(s.validatorAcceptRate)} | ${s.replacedByValidator} | ${pct(s.keywordCoverage)} | ${s.unknownDeclined} | ${n1(s.promptTokensPerSecond)} | ${n1(s.tokensPerSecond)} | ${s.avgSecondsPerAnswer.toFixed(1)} |`,
  );
  return [head, ...rows].join("\n");
}

const out: string[] = [];
out.push("# Model benchmarks — “Ask about Ankit”", "", "_Generated by `tools/bench/report.ts` from the JSON files in this folder. Do not edit by hand._", "");
out.push(
  "Every case runs through the **real** pipeline: guardrails → hybrid retrieval → routing → one grounded generation → deterministic validation. “Final answers correct” is what a visitor sees (a rejected draft is replaced by the verified instant answer, so it can still be correct). “Model drafts accepted” is how often the model's own wording survived validation — the honest measure of the model itself.",
  "",
);
if (final) {
  out.push(`## Final run — ${final.runAt.slice(0, 16).replace("T", " ")} UTC`, "", `Hardware: ${final.hardware}. ${final.evalCases} evaluation questions (guardrail cases excluded — they never reach a model). llama.cpp \`llama-server\`, context 4096, temperature 0.2, max 260 new tokens. Speeds come from llama-server's own timings on a fixed probe.`, "", table(final.results), "");
  const failures = final.results.flatMap((r: { summary: Summary; rows: { id: string; pass?: boolean; replaced?: boolean; issues?: string[] }[] }) =>
    r.rows.filter((x) => x.pass === false || x.replaced).map((x) => `| ${r.summary.model} | ${x.id} | ${x.pass === false ? "wrong" : "correct after replacement"} | ${(x.issues ?? []).join("; ").replace(/\|/g, "/")} |`),
  );
  if (failures.length) out.push("### Every replaced or wrong answer", "", "| Model | Case | Outcome | Validator findings |", "|---|---|---|---|", ...failures, "");
} else out.push("## Final run", "", "_Not run yet._", "");
if (speed) {
  out.push(`## CPU speed (standardised) — ${speed.runAt.slice(0, 16).replace("T", " ")} UTC`, "", `${speed.tool}. ${speed.hardware}. Speeds in the quality tables above are lower because they were measured on real ~850-token prompts while the machine was busy; use these for comparison.`, "", "| Model | GGUF size | Prefill (pp512) tok/s | Decode (tg128) tok/s |", "|---|---|---|---|");
  for (const r of speed.results) out.push(`| ${r.model} | ${r.sizeMB} MB | ${r.prefillTokS} ± ${r.prefillStd} | ${r.decodeTokS} ± ${r.decodeStd} |`);
  out.push("");
}
if (gpu) {
  out.push(`## In-browser (WebGPU) — ${gpu.runAt.slice(0, 16).replace("T", " ")} UTC`, "", `Browser: ${gpu.browserVersion}, visible window, real GPU.`, "", "| WebLLM build | Load (cached weights) | Result |", "|---|---|---|");
  for (const r of gpu.raw) {
    const run = r.runs?.at(-1);
    const x = run?.usage?.extra ?? {};
    out.push(`| ${r.modelId} | ${r.loadMs ? `${(r.loadMs / 1000).toFixed(1)} s` : "—"} | ${r.error ? `**${r.error}**` : `first token ${run.firstTokenMs} ms · prefill ${n1(x.prefill_tokens_per_s)} tok/s · decode ${n1(x.decode_tokens_per_s)} tok/s`} |`);
  }
  out.push("");
}
if (prelim) {
  out.push(`## Preliminary run — ${prelim.runAt.slice(0, 16).replace("T", " ")} UTC (superseded)`, "", "Run before the validator's false-alarm fixes and while the machine was also building the site and running browser tests, so speeds are depressed and the replacement counts include validator false alarms (e.g. `2024.` with a trailing period, “October” vs “Oct”). Kept for transparency; Gemma-3-1B was only measured here.", "", table(prelim.results), "");
}
writeFileSync(path.join(dir, "README.md"), out.join("\n"));
console.log("Wrote docs/benchmarks/README.md");
