/**
 * Turns the measured benchmark files into docs/benchmarks/README.md, so every
 * number in the docs comes straight from a run (nothing typed by hand).
 *   node bench/report.ts
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ROOT } from "../kb/content.ts";
import { draftAcceptance } from "./metrics.ts";

const dir = path.join(ROOT, "docs", "benchmarks");
const read = (f: string) => (existsSync(path.join(dir, f)) ? JSON.parse(readFileSync(path.join(dir, f), "utf8")) : null);
const PRELIM_FILE = "llm-benchmark-preliminary.json";
const final = read("llm-benchmark.json");
const prelim = read(PRELIM_FILE);
// Further final-code runs saved separately (`BENCH_OUT=llm-benchmark-<model>.json`) so they
// never overwrite llm-benchmark.json. Everything except the preliminary file joins the final table.
const extraFinal = readdirSync(dir)
  .filter((f) => /^llm-benchmark-.+\.json$/.test(f) && f !== PRELIM_FILE)
  .sort()
  .map((f) => ({ file: f, ...read(f) }));
const finalRuns: Run[] = [...(final ? [{ file: "llm-benchmark.json", ...final }] : []), ...extraFinal];
const gpu = read("webgpu-benchmark.json");
const speed = read("llama-bench.json");
const pct = (x: number) => `${Math.round(x * 100)}%`;
const n1 = (x: number | null | undefined) => (x === null || x === undefined ? "—" : x.toFixed(1));

type Summary = {
  model: string; params: string; quant: string; license: string; fileMB: number; ramMB: number | null; cases: number; errors: number;
  passRate: number; validatorAcceptRate: number; replacedByValidator: number; keywordCoverage: number; unknownDeclined: string;
  avgSecondsPerAnswer: number; avgGenerationSeconds: number; tokensPerSecond: number | null; promptTokensPerSecond?: number | null;
};
type Row = { id: string; kind?: string; mode?: string; pass?: boolean; replaced?: boolean; issues?: string[]; error?: string | null };
type Run = { file: string; runAt: string; hardware?: string; evalCases?: number; results: { summary: Summary; rows: Row[] }[] };
const stamp = (iso: string) => `${iso.slice(0, 16).replace("T", " ")} UTC`;

function table(results: { summary: Summary; rows: Row[] }[]) {
  const head = "| Model | Params | Quant | File | RAM | Final answers correct | Model drafts accepted by validator | Replaced | Keyword coverage | Unknowns declined | Prefill tok/s | Decode tok/s | Avg s / answer |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|";
  const rows = results.map(({ summary: s, rows: caseRows }) => {
    // Recomputed from the per-case rows (not summary.validatorAcceptRate), so files written
    // with the earlier formula are scored like new ones — see bench/metrics.ts.
    const drafts = draftAcceptance(caseRows.filter((r) => "pass" in r));
    const draftsCell = `${pct(drafts.rate)} (${drafts.accepted}/${drafts.called})`;
    // passRate is over the cases that produced an answer; a case that errored counts as not correct.
    const errors = s.errors ?? 0;
    const correct = Math.round(s.passRate * s.cases);
    const total = s.cases + errors;
    const correctCell = `${pct(correct / Math.max(1, total))} (${correct}/${total}${errors ? `, ${errors} errored` : ""})`;
    return `| ${s.model} (${s.license}) | ${s.params} | ${s.quant} | ${s.fileMB} MB | ${s.ramMB ?? "—"} MB | ${correctCell} | ${draftsCell} | ${s.replacedByValidator} | ${pct(s.keywordCoverage)} | ${s.unknownDeclined} | ${n1(s.promptTokensPerSecond)} | ${n1(s.tokensPerSecond)} | ${s.avgSecondsPerAnswer.toFixed(1)} |`;
  });
  return [head, ...rows].join("\n");
}

const out: string[] = [];
out.push("# Model benchmarks — “Ask about Ankit”", "", "_Generated by `tools/bench/report.ts` from the JSON files in this folder. Do not edit by hand._", "");
out.push(
  "Every case runs through the **real** pipeline: guardrails → hybrid retrieval → routing → one grounded generation → deterministic validation. “Final answers correct” is what a visitor sees (a rejected draft is replaced by the verified instant answer, so it can still be correct). “Model drafts accepted” is how often the model's own wording survived validation — the honest measure of the model itself: drafts accepted ÷ questions where the model was asked for a draft (questions declined deterministically or stopped by a guardrail never reach the model and are not counted). It is recomputed here from the per-case rows by `tools/bench/metrics.ts`; the `validatorAcceptRate` stored in result files written before that fix used a formula that also dropped *rejected* drafts on unknown-topic questions (Qwen2.5-0.5B was stored as 31/32 = 97 % instead of 31/33 = 94 %).",
  "",
);
if (finalRuns.length) {
  const hardware = [...new Set(finalRuns.map((r) => r.hardware ?? "unknown"))];
  const evalCases = [...new Set(finalRuns.map((r) => r.evalCases))];
  const setup = `${evalCases.length === 1 ? `${evalCases[0]} evaluation questions` : `**Different evaluation set sizes per run (${evalCases.join(" / ")})** — compare with care`} (guardrail cases excluded — they never reach a model). llama.cpp \`llama-server\`, context 4096, temperature 0.2, max 260 new tokens. Speeds come from llama-server's own timings on a fixed probe.`;
  if (finalRuns.length === 1) {
    out.push(`## Final run — ${stamp(finalRuns[0].runAt)}`, "", `Hardware: ${hardware[0]}. ${setup}`, "");
  } else {
    out.push(
      "## Final run",
      "",
      `Hardware: ${hardware.length === 1 ? hardware[0] : `**not identical across runs** (${hardware.join(" / ")})`}. ${setup}`,
      "",
      "Models were run separately (one result file each, so a later run never overwrites an earlier one). Throughput and seconds per answer depend on how loaded or throttled the laptop was during each run, so compare them only within one file; for a cross-model speed ranking use the llama-bench table below.",
      "",
      ...finalRuns.map((r) => `- \`${r.file}\` — ${stamp(r.runAt)}: ${r.results.map((x) => x.summary.model).join(", ")}`),
      "",
    );
  }
  out.push(table(finalRuns.flatMap((r) => r.results)), "");
  const failures = finalRuns.flatMap((run) =>
    run.results.flatMap((r) =>
      r.rows
        .filter((x) => !("pass" in x) || x.pass === false || x.replaced)
        .map((x) =>
          !("pass" in x)
            ? `| ${r.summary.model} | ${x.id} | error (no answer) | ${String(x.error ?? "unknown error").replace(/\|/g, "/")} |`
            : `| ${r.summary.model} | ${x.id} | ${x.pass === false ? "wrong" : "correct after replacement"} | ${(x.issues ?? []).join("; ").replace(/\|/g, "/")} |`,
        ),
    ),
  );
  if (failures.length) out.push("### Every replaced or wrong answer", "", "| Model | Case | Outcome | Validator findings |", "|---|---|---|---|", ...failures, "");
} else out.push("## Final run", "", "_Not run yet._", "");
const agentsRun = read("agent-execution.json");
if (agentsRun) {
  out.push(
    `## Agent execution (real inference) — ${stamp(agentsRun.runAt)}`,
    "",
    `Generated by \`tools/bench/agents.ts\`: ${agentsRun.scenarios} scenarios through the real orchestrator with **${agentsRun.model}** (${agentsRun.runtime}), embeddings ${agentsRun.embedding}. “Model tokens” counts tokens actually streamed by the model (0 = no model call: guardrail, honest decline, or a deliberately unavailable/hanging server). Failure scenarios use a closed port and a real server that never answers — not mocks. **${agentsRun.passed}/${agentsRun.scenarios} passed.**`,
    "",
    "| Scenario | What it checks | Agents (routing) | Answer | Model tokens | Validator | Time | Result |",
    "|---|---|---|---|---|---|---|---|",
  );
  for (const r of agentsRun.rows) {
    const v = r.validator ? (r.validator.replaced ? `replaced: ${r.validator.issues.slice(0, 2).join("; ")}` : r.validator.issues.length ? r.validator.issues.slice(0, 1).join("") : "kept") : "—";
    const agents = r.plan ? `${r.plan.agents.join(" + ")} (${r.plan.method})` : "— (stopped before routing)";
    out.push(`| ${r.id} | ${r.checks} | ${agents} | ${r.mode ?? "error"} | ${r.modelGeneratedTokens} | ${v.replace(/\|/g, "/")} | ${(r.timings.totalMs / 1000).toFixed(1)} s | ${r.pass ? "pass" : `**fail** (${Object.entries(r.criteria).filter(([, ok]) => !ok).map(([k]) => k).join(", ")})`} |`);
  }
  out.push("");
}
if (speed) {
  out.push(`## CPU speed (standardised) — ${speed.runAt.slice(0, 16).replace("T", " ")} UTC`, "", `${speed.tool}. ${speed.hardware}. Speeds in the quality tables above were measured on real ~850-token prompts under whatever load the machine had during each run, so they differ from these and between result files; use these for comparison. Large ± values mean the laptop CPU was throttling or shared during the measurement (e.g. prefill for the 1.5B model coming out faster than for the 1B model is not physically plausible), so read them as a rough ranking, not absolute numbers.`, "", "| Model | GGUF size | Prefill (pp512) tok/s | Decode (tg128) tok/s |", "|---|---|---|---|");
  for (const r of speed.results) out.push(`| ${r.model} | ${r.sizeMB} MB | ${r.prefillTokS} ± ${r.prefillStd} | ${r.decodeTokS} ± ${r.decodeStd} |`);
  out.push("");
}
if (gpu) {
  out.push(`## In-browser (WebGPU) — ${gpu.runAt.slice(0, 16).replace("T", " ")} UTC`, "", `Browser: ${gpu.browserVersion}, visible window, real GPU.`, "", "| WebLLM build | Load (cached weights) | Result |", "|---|---|---|");
  for (const r of gpu.raw) {
    const run = r.runs?.at(-1);
    const x = run?.usage?.extra ?? {};
    out.push(`| ${r.modelId} | ${r.loadMs ? `${(r.loadMs / 1000).toFixed(1)} s` : "—"} | ${r.error ? `**${r.error}**` : `first token ${run.firstTokenMs} ms · prefill ${n1(x.prefill_tokens_per_s)} tok/s · decode ${n1(x.decode_tokens_per_s)} tok/s`} |`);
  }
  out.push("");
}
if (prelim) {
  out.push(`## Preliminary run — ${prelim.runAt.slice(0, 16).replace("T", " ")} UTC (superseded)`, "", "Run before the validator's false-alarm fixes and while the machine was also building the site and running browser tests, so speeds are depressed and the replacement counts include validator false alarms (e.g. `2024.` with a trailing period, “October” vs “Oct”). Kept for transparency; Gemma-3-1B was only measured here.", "", table(prelim.results), "");
}
writeFileSync(path.join(dir, "README.md"), out.join("\n"));
console.log("Wrote docs/benchmarks/README.md");
